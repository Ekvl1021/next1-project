const { test } = require('node:test');
const assert = require('node:assert/strict');
require('dotenv').config();
const mongoose = require('mongoose');
const jwt = require('jsonwebtoken');
const prefix = `assessment_test_${process.pid}_${Date.now()}_`;
mongoose.pluralize(name => prefix + name.toLowerCase());
const app = require('../server');
const Course = require('../models/Course');
const Selection = require('../models/CourseSelection');
const { Assessment, Submission } = require('../models/Assessment');
test('publication, protected files, submissions, ownership and deadlines', async t => {
  await require('../config/db')();
  const server = app.listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  t.after(async () => {
    await new Promise(resolve => server.close(resolve));
    const collections = await mongoose.connection.db.listCollections({}, { nameOnly: true }).toArray();
    for (const collection of collections.filter(c => c.name.startsWith(prefix))) await mongoose.connection.db.dropCollection(collection.name);
    await mongoose.disconnect();
  });
  await Submission.init();
  await Course.create({ id: 1, title: 'Test', teacher: 'teacher', schedule: 'Monday', room: 'A' });
  await Selection.create({ studentId: '3', courseId: '1', status: 'approved' });
  const roles = { teacher: ['2', 'teacher'], other: ['4', 'teacher'], student: ['3', 'student'], outsider: ['5', 'student'] };
  const request = (path = '', method = 'GET', actor = 'teacher', body) => fetch(`http://127.0.0.1:${server.address().port}/api/assessments${path}`, { method, headers: { 'Content-Type': 'application/json', ...(roles[actor] ? { Authorization: `Bearer ${jwt.sign({ sub: roles[actor][0], username: actor, role: roles[actor][1] }, process.env.JWT_SECRET, { expiresIn: '5m' })}` } : {}) }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
  const attachment = { name: 'example.txt', data: Buffer.from('Example file').toString('base64') };
  const fixture = { courseId: '1', kind: 'assignment', title: 'Example', description: 'Instructions', dueAt: new Date(Date.now() + 86400000).toISOString(), attachment };
  assert.equal((await request('', 'GET', 'none')).status, 401);
  for (const actor of ['student']) assert.equal((await request('', 'POST', actor, fixture)).status, 403);
  assert.equal((await request('', 'POST', 'teacher', { ...fixture, attachment: { name: 'bad', data: '!' } })).status, 400);
  const created = await request('', 'POST', 'teacher', fixture); assert.equal(created.status, 201);
  const { id } = await created.json();
  assert.equal((await request('', 'POST', 'teacher', { ...fixture, kind: 'exam' })).status, 201);
  assert.equal((await request(`/${id}/file`, 'GET', 'outsider')).status, 200);
  assert.deepEqual(await (await request(`/${id}/file`, 'GET', 'student')).json(), attachment);
  assert.equal((await (await request('', 'GET', 'outsider')).json()).items.length, 2);
  assert.equal((await request(`/${id}/submission`, 'PUT', 'student', {})).status, 400);
  assert.equal((await request(`/${id}/submission`, 'PUT', 'student', { answer: 'Answer', attachment })).status, 200);
  assert.equal((await request(`/${id}/submission`, 'PUT', 'outsider', { answer: 'No selection required' })).status, 200);
  const item = (await (await request()).json()).items.find(row => row.id === id);
  assert.equal(item.submissions[0].answer, 'Answer');
  assert.equal(item.attachment.data, undefined);
  assert.equal(item.submissions[0].attachment.data, undefined);
  assert.deepEqual(await (await request(`/${id}/file?submission=${item.submissions[0].id}`)).json(), attachment);
  await Selection.create({ studentId: '5', courseId: '1', status: 'pending' });
  const pending = await (await request('', 'GET', 'outsider')).json();
  assert.equal(pending.items.length, 2);
  assert.equal(pending.courses[0].canSubmit, true);
  assert.equal((await request(`/${id}/submission`, 'PUT', 'outsider', { answer: 'Pending' })).status, 200);
  await Selection.updateOne({ studentId: '5', courseId: '1' }, { status: 'approved' });
  assert.equal((await request(`/${id}/file?submission=${item.submissions[0].id}`, 'GET', 'outsider')).status, 404);
  assert.equal((await request(`/${id}/submission`, 'PUT', 'student', { answer: 'Updated' })).status, 200);
  assert.equal(await Submission.countDocuments({ assessmentId: id }), 2);
  assert.equal((await (await request('', 'GET', 'other')).json()).items.find(row => row.id === id).submissions.length, 2);
  assert.equal((await request('', 'POST', 'other', { ...fixture, title: 'Other teacher' })).status, 201);
  await Assessment.updateOne({ _id: id }, { dueAt: new Date(Date.now() - 1000) });
  assert.equal((await request(`/${id}/submission`, 'PUT', 'student', { answer: 'Late' })).status, 400);
  assert.equal((await request('/bad/file')).status, 400);
});
